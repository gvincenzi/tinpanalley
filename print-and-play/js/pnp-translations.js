let currentPnpLang = 'it';

function getPnpValue(obj, path) {
  return path.split('.').reduce((acc, key) => (acc && acc[key] !== undefined ? acc[key] : null), obj);
}

function updateInkButtonLabel() {
  const btn = document.getElementById('toggleInkBtn');
  if (!btn) return;
  const isInk = document.body.classList.contains('ink-friendly');
  btn.textContent = isInk
    ? PNP_TRANSLATIONS[currentPnpLang].common.inkOn
    : PNP_TRANSLATIONS[currentPnpLang].common.inkOff;
}

function toggleInkMode() {
  document.body.classList.toggle('ink-friendly');
  updateInkButtonLabel();
}

function setPnpLanguage(lang, pageKey) {
  if (!PNP_TRANSLATIONS[lang]) lang = 'it';
  currentPnpLang = lang;
  document.documentElement.lang = lang;

  if (pageKey && PNP_TRANSLATIONS[lang][pageKey]) {
    document.title = PNP_TRANSLATIONS[lang][pageKey].docTitle;
  }

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = getPnpValue(PNP_TRANSLATIONS[lang], key);
    if (value !== null) {
      el.innerHTML = value;
    }
  });

  const btnIt = document.getElementById('btn-it');
  const btnFr = document.getElementById('btn-fr');
  if (btnIt) btnIt.classList.toggle('active', lang === 'it');
  if (btnFr) btnFr.classList.toggle('active', lang === 'fr');

  updateInkButtonLabel();
  localStorage.setItem('tinpanalley_lang', lang);
}

function initPnpLanguage(pageKey) {
  const saved = localStorage.getItem('tinpanalley_lang');
  if (saved && PNP_TRANSLATIONS[saved]) {
    setPnpLanguage(saved, pageKey);
  } else {
    const browserLang = (navigator.language || 'it').toLowerCase();
    setPnpLanguage(browserLang.startsWith('fr') ? 'fr' : 'it', pageKey);
  }
}
